    from pg_constraint
    where conname = 'user_operations_role_check'
      and conrelid = 'public.user_operations'::regclass
  ) then
    alter table public.user_operations
      add constraint user_operations_role_check
      check (role in ('owner', 'admin', 'operator', 'technician', 'reviewer', 'viewer'));
