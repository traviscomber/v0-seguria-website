create table if not exists public.wildlife_territorial_access_log (
  id bigint generated by default as identity primary key,
  operation_id uuid null references public.operations(id) on delete set null,
  actor_user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  resource_type text not null,
  resource_id text null,
  coordinate_precision text null check (coordinate_precision is null or coordinate_precision in ('exact', 'generalized', 'hidden')),
  ip_address inet null,
  user_agent text null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists wildlife_territorial_access_operation_created_idx
  on public.wildlife_territorial_access_log(operation_id, created_at desc)
  where operation_id is not null;

create index if not exists wildlife_territorial_access_actor_created_idx
  on public.wildlife_territorial_access_log(actor_user_id, created_at desc);

alter table public.wildlife_territorial_access_log enable row level security;

drop policy if exists wildlife_territorial_access_select on public.wildlife_territorial_access_log;
create policy wildlife_territorial_access_select
  on public.wildlife_territorial_access_log
  for select
  to authenticated
  using (
    actor_user_id = (select auth.uid())
    or exists (
      select 1
      from public.user_operations access_link
      where access_link.user_id = (select auth.uid())
        and access_link.operation_id = wildlife_territorial_access_log.operation_id
        and access_link.role in ('owner', 'admin')
    )
  );

revoke all on public.wildlife_territorial_access_log from anon;
revoke insert, update, delete on public.wildlife_territorial_access_log from authenticated;
grant select on public.wildlife_territorial_access_log to authenticated;

with single_operation as (
  select user_id, max(operation_id::text)::uuid as operation_id
  from public.user_operations
  group by user_id
  having count(*) = 1
)
